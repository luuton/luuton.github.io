% IPv4
mtext(ax,90,800,'IPv4 首部（20 B 基本首部）','halign','left','fontsize',12.5,'fontweight','bold','color',[0.14 0.40 0.72]);
v4={ {'版本',4,[0.90 0.90 0.90]}, {'首部长度',4,[0.90 0.90 0.90]}, {'TOS',8,[0.86 0.94 0.86]}, ...
