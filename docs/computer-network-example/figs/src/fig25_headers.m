     {'首部校验和',16,[0.90 0.90 0.90]}, {'源 IP 地址',32,[0.82 0.90 0.98]}, ...
     {'目的 IP 地址',32,[0.82 0.90 0.98]}, {'选项（可变）',24,[0.94 0.94 0.94]} };
mbitstrip(ax,110,670,980,44,v4,'fontsize',9,'showbits',false,'rotate',true);

% TCP
